@pytest.mark.asyncio
async def test_revoking_a_key_stops_new_receipts_but_keeps_old_ones(
    client, principal_maker, signer
):
    """Revocation is not a time machine."""
    p = await principal_maker()
    await receipts.register_key(p["id"], signer.pubkey)
    first = signer()
    await receipts.submit(principal=p, receipt=first)

    await receipts.revoke_key(p["id"], signer.pubkey)
    with pytest.raises(receipts.ReceiptError):
        await receipts.submit(principal=p, receipt=signer(previous_hash=first["receipt_id"]))
    assert await receipts.chain_head(p["id"]) == first["receipt_id"]


