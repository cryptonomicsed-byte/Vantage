@pytest.mark.asyncio
async def test_a_receipt_that_forks_the_chain_is_refused(client, principal_maker, signer):
    """Two receipts naming the same predecessor means one is not part of this
    history. Accepting both would make the chain decorative."""
    p = await principal_maker()
    await receipts.register_key(p["id"], signer.pubkey)
    a = signer()
    await receipts.submit(principal=p, receipt=a)
    await receipts.submit(principal=p, receipt=signer(previous_hash=a["receipt_id"]))

    fork = signer(previous_hash=a["receipt_id"])
    with pytest.raises(receipts.ReceiptError) as excinfo:
        await receipts.submit(principal=p, receipt=fork)
    assert "does not extend" in str(excinfo.value)


@pytest.mark.asyncio
async def test_two_principals_keep_separate_chains(client, principal_maker, signer):
    one, two = await principal_maker(), await principal_maker()
    for p in (one, two):
        await receipts.register_key(p["id"], signer.pubkey)
    a = signer(agent_id="one")
    await receipts.submit(principal=one, receipt=a)
    b = signer(agent_id="two")
    result = await receipts.submit(principal=two, receipt=b)
    assert result["chain_position"] == "start"


