def test_an_accepted_receipt_does_not_mint_a_new_event_kind():
    """1902 is the ecosystem's attestation schema, and it is explicitly
    attestor-agnostic -- a runtime confirming its own execution is an
    attestor like any other."""
    from backend import nostr_kinds

    assert receipts.KIND_ATTESTATION == nostr_kinds.kind("attestation")
    assert not nostr_kinds.is_ours(receipts.KIND_ATTESTATION)


@pytest.mark.asyncio
async def test_a_full_range_u64_nonce_survives_storage(client, principal_maker, signer):
    """The kernel draws its nonce from the whole u64 range, and SQLite's
    INTEGER is signed 64-bit -- so an INTEGER column rejects roughly half of
    all real receipts. This is the case that found that."""
    p = await principal_maker()
    await receipts.register_key(p["id"], signer.pubkey)
    receipt = signer(nonce=2**64 - 1)
    result = await receipts.submit(principal=p, receipt=receipt)
    assert result["accepted"] is True

    chain = await receipts.chain_for_principal(p["id"])
    assert chain[0]["receipt_id"] == receipt["receipt_id"]
