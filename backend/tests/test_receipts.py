"""Runtime receipts, checked against a receipt the real kernel produced.

The vector in KERNEL_RECEIPT was generated by compiling
`Receipt::calculate_id` and `new_merkle` from omokoda-core verbatim against
the same blake3 and ed25519-dalek crates the kernel uses, and running them.
It is here so that a change to this verifier that "looks right" but hashes
the timestamp as bytes instead of as its decimal string -- or verifies the
signature against the decoded hash instead of the hex string -- fails
immediately rather than rejecting every real receipt in production.
"""
