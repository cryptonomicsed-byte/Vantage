@pytest_asyncio.fixture
async def signer():
    """A key we hold, for building chains longer than one receipt."""
    from nacl.signing import SigningKey

    key = SigningKey(bytes.fromhex("2b" * 32))

    def make(previous_hash="", action="act", nonce=None, timestamp=1756000001,
             agent_id="kernel-agent"):
        # A real nonce is a full random u64. Defaulting to one here keeps two
        # tests from colliding on the same receipt id, and exercises the
        # range that does not fit a signed 64-bit column.
        if nonce is None:
            nonce = secrets.randbits(64)
        body = {
            "agent_id": agent_id, "action": action,
            "payload": receipts._blake3_hex(action.encode(), b"{}"),
            "previous_hash": previous_hash, "merkle_root": "root",
            "timestamp": timestamp, "nonce": nonce,
        }
        body["receipt_id"] = receipts.compute_receipt_id(body)
        body["signature"] = key.sign(body["receipt_id"].encode()).signature.hex()
        return body

    make.pubkey = bytes(key.verify_key).hex()
    return make


# ── the hash, against the real kernel ────────────────────────────────────────

def test_the_receipt_id_matches_the_one_the_kernel_computed():
    assert receipts.compute_receipt_id(KERNEL_RECEIPT) == KERNEL_RECEIPT["receipt_id"]


def test_the_kernel_signature_verifies():
    receipts.verify_signature(
        KERNEL_RECEIPT["receipt_id"], KERNEL_RECEIPT["signature"], KERNEL_PUBKEY
    )


def test_the_signature_is_over_the_hex_string_not_the_decoded_hash():
    """The kernel signs `receipt_id.as_bytes()`. Verifying against the
    decoded 32 bytes is the plausible mistake, and it would reject every
    real receipt while looking entirely reasonable."""
    from nacl.signing import VerifyKey

    key = VerifyKey(bytes.fromhex(KERNEL_PUBKEY))
    signature = bytes.fromhex(KERNEL_RECEIPT["signature"])
    key.verify(KERNEL_RECEIPT["receipt_id"].encode(), signature)  # the real one
    with pytest.raises(Exception):
        key.verify(bytes.fromhex(KERNEL_RECEIPT["receipt_id"]), signature)


def test_the_integers_are_hashed_as_decimal_strings():
    """Hashing them as raw bytes produces a different id. This pins which."""
    variant = dict(KERNEL_RECEIPT, timestamp=KERNEL_RECEIPT["timestamp"] + 1)
    assert receipts.compute_receipt_id(variant) != KERNEL_RECEIPT["receipt_id"]


def test_a_receipt_missing_a_field_is_named_not_guessed():
    partial = {k: v for k, v in KERNEL_RECEIPT.items() if k != "merkle_root"}
    with pytest.raises(receipts.ReceiptError) as excinfo:
        receipts.compute_receipt_id(partial)
    assert "merkle_root" in str(excinfo.value)


def test_a_tampered_field_changes_the_id():
    tampered = dict(KERNEL_RECEIPT, action="rm -rf")
    assert receipts.compute_receipt_id(tampered) != KERNEL_RECEIPT["receipt_id"]


