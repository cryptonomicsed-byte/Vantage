from backend import work_refs as wr
from backend.db import get_db

# Produced by the kernel's own code paths. Do not regenerate by hand.
KERNEL_RECEIPT = {
    "agent_id": "agent-7",
    "action": "run_tests",
    "payload": "6a25564eebe3ccdfa2ed03fa8fa84de75532ddd8da03b347d6c1b2f5c8904255",
    "receipt_id": "44cb19ec7bf6a49d53821715185f781f8d99ff6cffbd7d93a07d186face23822",
    "previous_hash": "",
    "merkle_root": "abc123",
    "signature": (
        "45052ddccce6c77eb702a74278c9c101a7fa1c6793075737db55ff6a73f30ff7"
        "2f9dd97d07641bdc5a7520b6c67c397c6ef7a09d38e08a1e5759df111557260c"
    ),
    "timestamp": 1756000000,
    "nonce": 11400714819323198485,
}
KERNEL_PUBKEY = "197f6b23e16c8532c6abc838facd5ea789be0c76b2920334039bfa8b3d368d61"


